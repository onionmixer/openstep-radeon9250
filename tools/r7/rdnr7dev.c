/*
 * rdnr7dev.c - R7b: submit one client stream through the CHARACTER DEVICE
 * (docs/R7_PLAN.md 10).  Pure C.
 *
 * Build on the target:
 *   cc -O -Wall -o rdnr7dev rdnr7dev.c
 *
 * There is no -lDriver and no #import on purpose.  R7a's tool reached the
 * driver through IODeviceMaster, which is Objective-C; the Mesa acceleration
 * library cannot link Objective-C, so the whole point of this one is to prove
 * the same verifier, the same buffer and the same draw are reachable with
 * nothing but open, ioctl and mmap.  If this file ever needs an Objective-C
 * header, R7b has failed and the failure should be loud.
 *
 * Usage:
 *   rdnr7dev <runid> <major> <case> [n=<count>] [unknown] [hold]
 *     major    the driver's character major (the driver pins it; 38 on this card)
 *     case     0 .. CP_R7_CASE_COUNT-1, the streams tools/r7/verify_oracle.py built
 *     n=<count>  submit a different count than the case has, to reach the kernel's
 *                own limit checks before the verifier (0 and 2017 are the ones)
 *     unknown  send a command in this group that the driver does not answer, and
 *              stop -- gate E: it must be refused AND leave its number in the log
 *     hold     open the node a SECOND time while this one holds it, and stop --
 *              gate C: it must be refused.  That it changed nothing is what the
 *              runs after it show, so this mode does not submit.
 *
 * The stream table is GENERATED (tools/r7/verify_oracle.py --c-cases) with
 * win = 0; this boot's winStart comes back from CAPS and is added to the words
 * the generated mask marks.  Nothing about a boot is baked in.
 *
 * Exit codes:
 *   0  submitted (whatever the verdict)   2  usage
 *   3  mknod/open failed                  4  CAPS refused or disagrees with this build
 *   5  mmap refused                       6  SUBMIT could not be sent at all
 *
 * Every line starts "RDNR7B ".
 */

