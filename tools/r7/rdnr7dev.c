/* this is the 4.2BSD mmap: the address must be the caller's already, so the
   place is vm_allocated first and then mapped over (R4c, and the Matrox
   probe's OSMGAMesaProbe.c:275-292 records the same discovery) */
extern caddr_t mmap(caddr_t, int, int, int, int, off_t);
/* this libc's headers declare none of these, and an implicit declaration is a
   guess: say what they are rather than let the compiler assume */
