/*
 * rdnr7sub.m - stage one R7a client stream into OSRDNDisplay (docs/R7_PLAN.md 3, 5).
 *
 * Build on the target:
 *   cc -O -Wall -o rdnr7sub rdnr7sub.m -lDriver
 *
 * Usage:
 *   rdnr7sub <runid> <build hex8> <case> [pieces]
 *     case   0 .. CP_R7_CASE_COUNT-1, the streams tools/r7/verify_oracle.py built
 *     pieces how many appends to split the stream into (default 1; the U2 case of
 *            docs/R7_PLAN.md 5 is case 0 with pieces 3)
 *
 * Staging touches no hardware: it copies words into the driver's own buffer.  Drawing them is a
 * separate call, "rdnr5cp <runid> <build> zclear 171", which goes through the mode claim like
 * every other case -- so a client cannot reach the words the verifier judged.
 *
 * The stream table is GENERATED (tools/r7/verify_oracle.py --c-cases) with win = 0, and the
 * surface addresses get this boot's winStart added here, using the mask generated beside them.
 * Nothing about a boot is baked into the table.
 *
 * Exit codes:
 *   0  staged     2  usage     3  Display0 not found
 *   4  RDNR2b0State is not this build        5  the driver refused an append
 *
 * Every line starts "RDNR7 ".
 */

