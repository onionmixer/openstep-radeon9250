int
main(int argc, char **argv)
{
    IODeviceMaster *master;
    IOObjectNumber obj;
    IOString kind;
    IOReturn r;
    unsigned state[STATE_COUNT], vmap[VMAP_COUNT], msg[R7_HEAD + R7_APPEND_MAX];
    unsigned count, token, winStart;
    unsigned long runid, build, which, pieces, first, n, done, k, take;
    char *end;

    if (argc != 4 && argc != 5) {
        printf("RDNR7 usage: rdnr7sub <runid> <build hex8> <case> [pieces]\n");
        return 2;
    }
    runid = strtoul(argv[1], &end, 10);
    if (*end != '\0') {
        printf("RDNR7 bad runid %s\n", argv[1]);
        return 2;
    }
    build = strtoul(argv[2], &end, 16);
    if (*end != '\0') {
        printf("RDNR7 bad build %s\n", argv[2]);
        return 2;
    }
    which = strtoul(argv[3], &end, 10);
    if (*end != '\0' || which >= (unsigned long)CP_R7_CASE_COUNT) {
        printf("RDNR7 bad case %s (0 .. %d)\n", argv[3], CP_R7_CASE_COUNT - 1);
        return 2;
    }
    pieces = 1UL;
    if (argc == 5) {
        pieces = strtoul(argv[4], &end, 10);
        if (*end != '\0' || pieces == 0UL || pieces > 16UL) {
            printf("RDNR7 bad pieces %s (1 .. 16)\n", argv[4]);
            return 2;
        }
    }
    first = cpR7Cases[which][0];
    n = cpR7Cases[which][1];
    token = (unsigned)((runid * 2654435761UL) | 1UL);   /* never 0: 0 means "nobody owns it" */

    master = [IODeviceMaster new];
    r = (master == nil) ? IO_R_NO_DEVICE
                        : [master lookUpByDeviceName:"Display0" objectNumber:&obj deviceKind:&kind];
    if (r != IO_R_SUCCESS) {
        printf("RDNR7 exit=3 lookup r=%d\n", (int)r);
        return 3;
    }
    count = STATE_COUNT;
    r = [master getIntValues:state forParameter:STATE_PARAM objectNumber:obj count:&count];
    if (r != IO_R_SUCCESS || count != STATE_COUNT || state[1] != (unsigned)build) {
        printf("RDNR7 exit=4 state r=%d build=%08x\n", (int)r, state[1]);
        return 4;
    }
    count = VMAP_COUNT;
    r = [master getIntValues:vmap forParameter:VMAP_PARAM objectNumber:obj count:&count];
    if (r != IO_R_SUCCESS || count != VMAP_COUNT) {
        printf("RDNR7 exit=4 vmap r=%d\n", (int)r);
        return 4;
    }
    winStart = vmap[6];                 /* the engine window's start: the card address surfaces use */
    printf("RDNR7 begin runid=%lu build=%08lx case=%lu words=%lu pieces=%lu win=%08x token=%08x\n",
           runid, build, which, n, pieces, winStart, token);

    msg[0] = R7_MAGIC;
    msg[1] = R7_OP_RESET;
    msg[2] = token;
    msg[3] = 0;
    r = [master setIntValues:msg forParameter:R7_PARAM objectNumber:obj count:R7_HEAD];
    if (r != IO_R_SUCCESS) {
        printf("RDNR7 exit=5 reset r=%d\n", (int)r);
        return 5;
    }
    done = 0UL;
    while (done < n) {
        take = (n - done + pieces - 1UL) / pieces;
        if (take > (unsigned long)R7_APPEND_MAX)
            take = (unsigned long)R7_APPEND_MAX;
        if (pieces > 1UL)
            pieces--;
        msg[0] = R7_MAGIC;
        msg[1] = R7_OP_APPEND;
        msg[2] = token;
        msg[3] = (unsigned)take;
        for (k = 0; k < take; k++)
            msg[R7_HEAD + k] = (unsigned)(cpR7Pool[first + done + k] +
