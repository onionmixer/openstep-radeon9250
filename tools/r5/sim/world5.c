/* ---- the GART and the GPU's memory ------------------------------------------- */

static int
agpCovers(unsigned long a)
{
    unsigned long v = R(0x014c), lo = (v & 0xffffUL) << 16, hi = (v & 0xffff0000UL) | 0xffffUL;

    return lo <= hi && a >= lo && a <= hi;
}

/* a GPU address to a block word index, or -1 (a hang on the machine) */
static long
gpuWord(unsigned long a, int write)
{
    unsigned long lo = R(0x01dc), hi = R(0x01e0), pte, phys, tbl;

    if (agpCovers(a)) {
        fail("a GPU access landed in a live AGP aperture", a, R(0x014c));
        return -1;
    }
    if ((R(0x01d0) & 1UL) == 0UL || a < lo || a > hi) {
        fail(write ? "a GPU write outside the translated window" : "a GPU read outside the translated window",
             a, R(0x01d0));
        return -1;
    }
    tbl = R(0x01d8);
    if (tbl < PHYS0 || tbl + ((hi - lo) >> 12) * 4UL + 4UL > PHYS0 + CP_BLOCK_BYTES) {
        fail("the GART table is not in the block", tbl, hi - lo);
        return -1;
    }
    pte = gpuView[(tbl - PHYS0) / 4 + ((a - lo) >> 12)];
    phys = (pte & 0xfffff000UL) + (a & 0xfffUL);
    if (phys < PHYS0 || phys >= PHYS0 + CP_BLOCK_BYTES) {
        fail("a PTE points outside the block", a, pte);
        return -1;
    }
    return (long)((phys - PHYS0) / 4);
}

static unsigned long
gpuRead(unsigned long a)
{
    long w = gpuWord(a, 0);

    return (w < 0) ? 0xffffffffUL : gpuView[w];
}

static void
gpuWrite(unsigned long a, unsigned long v)
{
    long w = gpuWord(a, 1);

    if (w < 0)
        return;
    gpuView[w] = v;
    blockMem[w] = v;                /* the CPU sees what the GPU wrote (snooped) */
}

/* ---- the CP ---------------------------------------------------------------------- */

static unsigned long
ringWords(void)
{
    return 2UL << (R(0x0704) & 0x3fUL);        /* 8 << size_l2qw bytes */
}

static int
cpRuns(void)
{
    int k;

    if ((R(0x0740) & 0xf0000000UL) == 0UL)
        return 0;
    if (meWrites != 512 || meBad)
        return 0;
    for (k = 0; k < 256; k++)
        if (meram[2 * k] != osrdnCpUcode[k][1] || meram[2 * k + 1] != osrdnCpUcode[k][0])
            return 0;
    if (simNeedReset && !resetAfterLoad)
        return 0;
    return !simNeverAdvance;
}

static void
cpRegWrite(unsigned long reg, unsigned long v)
{
    if (reg + 4 > MMIO_BYTES) {
        fail("PACKET0 outside MMIO", reg, v);
        return;
    }
    if (simTrace3d)
        printf("R6W %04lx %08lx\n", reg, v);
    if (reg == 0x1c24 && simDropDepthOffset)
        return;
    if (reg == 0x2140 && simVapSticky)
        v |= 0x100UL;
    R(reg) = v;
    if (reg == 0x143c) {
        /* G3d: DST_HEIGHT_WIDTH written -- the register-driven solid fill (X driver RADEONSolid):
           GMC solid 32 bpp paint, DP_CNTL left-to-right top-to-bottom, DST_PITCH_OFFSET, DST_Y_X,
           DP_BRUSH_FRGD_CLR through DP_WRITE_MASK */
        unsigned long gmc = R(0x146c), po = R(0x142c), yx = R(0x1438), colour = R(0x147c), wm = R(0x16cc);
        unsigned long addr, pitch, x, y, w, h, yy, xx, k2;

        if ((gmc & 0x2UL) == 0UL || ((gmc >> 4) & 0xfUL) != 13UL || ((gmc >> 8) & 0xfUL) != 6UL ||
            ((gmc >> 16) & 0xffUL) != 0xf0UL) {
            fail("a fill whose GMC is not a solid 32 bpp paint", gmc, 0);
            return;
        }
        if (R(0x16c0) != 3UL) {
            fail("a fill without DP_CNTL left-to-right, top-to-bottom", R(0x16c0), 0);
            return;
        }
        addr = (po & 0x3fffffUL) << 10;
        pitch = (po >> 22) * 64UL;
        y = yx >> 16; x = yx & 0xffffUL; h = v >> 16; w = v & 0xffffUL;
        if (addr < WIN0 || pitch == 0UL) {
            fail("a fill's destination is not in the block", addr, pitch);
            return;
        }
        for (yy = 0; yy < h; yy++)
            for (xx = 0; xx < w; xx++) {
                k2 = (addr - WIN0 + (y + yy) * pitch + (x + xx) * 4UL) / 4UL;
                if (k2 >= sizeof vram / sizeof vram[0]) {
                    fail("a fill paints past the block", k2, 0);
                    return;
                }
                vram[k2] = (vram[k2] & ~wm) | (colour & wm);
            }
        paints++;
    }
    if (reg >= 0x15e0 && reg <= 0x15f4) {
        unsigned long bit = 1UL << ((reg - 0x15e0) / 4);

        if (R(0x0770) & bit)
            gpuWrite(R(0x0774) + (reg - 0x15e0), v);    /* scratch writeback */
    }
}

/* execute up to n words */
/* ---- R6a: the fake 3D, the precedent (R6c: and its colour) ------------------------ */
static float
r6f(unsigned long u)
{
    union { unsigned int u; float f; } x;

    x.u = (unsigned int)u;
    return x.f;
}

static unsigned long
r6Mba(unsigned long pitch, unsigned long x, unsigned long y)     /* Mesa r200_span.c r200_mba_z32 */
{
    unsigned long b = ((y & 0x7ffUL) >> 4) * ((pitch & 0xfffUL) >> 5) + ((x & 0x7ffUL) >> 5);
    unsigned long par = (pitch & 0x20UL) ? (b & 1UL) : ((b & 1UL) ^ ((y >> 4) & 1UL));

    return (((x >> 0) & 1UL) << 2) | (((y >> 0) & 1UL) << 3) | (((x >> 1) & 1UL) << 4) | (((y >> 1) & 1UL) << 5) |
           (((x >> 3) & 1UL) << 6) | (((x >> 4) & 1UL) << 7) | (((x >> 2) & 1UL) << 8) | (((y >> 2) & 1UL) << 9) |
           (((y >> 3) & 1UL) << 10) | (par << 11) | ((b >> 1) << 12);
}

/* R6f (docs/R6F_PLAN.md 3-2, 5): Mesa r200_span.c r200_mba_z16 -- written here from Mesa, not from the
   driver, so the driver's copy is checked against it */
static unsigned long
r6MbaZ16(unsigned long pitch, unsigned long x, unsigned long y)
{
    unsigned long b = ((y & 0x7ffUL) >> 4) * ((pitch & 0xfffUL) >> 6) + ((x & 0x7ffUL) >> 6);
    unsigned long par = (pitch & 0x40UL) ? (b & 1UL) : ((b & 1UL) ^ ((y >> 4) & 1UL));

    return (((x >> 0) & 1UL) << 1) | (((y >> 0) & 1UL) << 2) | (((x >> 1) & 1UL) << 3) | (((y >> 1) & 1UL) << 4) |
           (((x >> 2) & 1UL) << 5) | (((x >> 4) & 1UL) << 6) | (((x >> 5) & 1UL) << 7) | (((x >> 3) & 1UL) << 8) |
           (((y >> 2) & 1UL) << 9) | (((y >> 3) & 1UL) << 10) | (par << 11) | ((b >> 1) << 12);
}

/* R6f: the model's z conversion, exact from the float's bits (shifts only: the -m32 build has no
   64-bit division): z (2^n - 1) rounded half up (up 1) -- ONE rule of tools/r6/depth_oracle.py's
   space, ('qNone', 'm1', 'up'), for the triangles, whose depth is their FIRST vertex's z (the model
   does not interpolate: R6f gates the anchors, the interpolation is recorded) -- or floored (up 0)
   for the R6a boxes, what the model always drew there (zclear_oracle 'trunc'; the old float
   product was x87 extended precision at -O0, so 0.5 gave 0x7fffff) */
static unsigned long
r6Conv(unsigned long u, int bits, int up)
{
    unsigned long top = (1UL << bits) - 1UL;
    long e = (long)((u >> 23) & 0xffUL) - 127L;
    unsigned long long p, m = (unsigned long long)((u & 0x7fffffUL) | 0x800000UL), v;
    long sh;

    if ((u & 0x7fffffffUL) == 0UL)
        return 0UL;
    if (u & 0x80000000UL)
        return 0UL;
    p = m * (unsigned long long)top;             /* z (2^n - 1) = p 2^(e - 23) */
    sh = 23L - e;
    if (sh <= 0)
        return top;                              /* z >= 1 */
    if (sh > 62)
        return 0UL;
    v = (p + (up ? (1ULL << (sh - 1)) : 0ULL)) >> sh;
    return v > top ? top : (unsigned long)v;
}

/* R6d (docs/R6D_PLAN.md 10, 13): TRIANGLES under ONE rasterization rule -- the one the machine
   follows (vertices truncated to 1/16 pixel, samples at pixel + 1/2, samples on an edge belong
   to top and left edges, winding-blind).  R6e (docs/R6E_PLAN.md 9): with SE_CNTL's diffuse
   field GOURAUD every lane is interpolated by ONE rule -- slopes floored to 2^-8 and evaluated
   from vertex 0, the byte floored: tools/r6/gouraud_oracle.py must find exactly this rule.  tools/r6/tri_oracle.py must
   find exactly this rule among its 4032 hypotheses from what this model draws.  Exact:
   a float32 vertex >= 0.5 is a multiple of 2^-24, so coordinates are integers at 2^24 and
   the edge products stay below 2^62. */
static long long
r6Fix(unsigned long u)
{
    long long n = (long long)((double)r6f(u) * 16777216.0);

    return n - n % (1LL << 20);                 /* truncate to 1/16 (positive coordinates): the MEASURED
                                                   rule, docs/R6D_PLAN.md 13 -- was 1/8 before the machine said */
}

static long long
r6FloorDiv(long long a, long long b)            /* floor(a / b), b > 0 -- in 32 bits: the -m32 host
                                                   build has no libgcc for 64-bit division; the
                                                   magnitudes fit (python: |a| < 3.9e8, b < 2^20) */
{
    long qa, qb, q;

    if (a > 2147483647LL || a < -2147483647LL || b <= 0 || b > 2147483647LL) {
        fail("a Gouraud division outside 32 bits", (unsigned long)a, (unsigned long)b);
        return 0;
    }
    qa = (long)a;
    qb = (long)b;
    q = qa / qb;
    return (qa % qb != 0 && qa < 0) ? q - 1 : q;
}

/* one lane of a Gouraud pixel: positions in 1/16 pixel (the 1/16-truncated vertices),
   slopes floored to 1/256, value = c0 + qx*(sx-x0) + qy*(sy-y0) in 1/4096, floored */
static unsigned long
r6Gouraud(const long long *X, const long long *Y, const unsigned long *c, long long sx16, long long sy16)
{
    long long A = (X[1] - X[0]) * (Y[2] - Y[0]) - (X[2] - X[0]) * (Y[1] - Y[0]);
    long long nx = ((long long)c[1] - (long long)c[0]) * (Y[2] - Y[0]) - ((long long)c[2] - (long long)c[0]) * (Y[1] - Y[0]);
    long long ny = ((long long)c[2] - (long long)c[0]) * (X[1] - X[0]) - ((long long)c[1] - (long long)c[0]) * (X[2] - X[0]);
    long long kx, ky, v;

    if (A < 0) {
        A = -A; nx = -nx; ny = -ny;
    }
    kx = r6FloorDiv(nx * 16LL * 256LL, A);          /* dC/dx = nx*16/A per pixel, in 1/256 */
    ky = r6FloorDiv(ny * 16LL * 256LL, A);
    v = r6FloorDiv((long long)c[0] * 4096LL + kx * (sx16 - X[0]) + ky * (sy16 - Y[0]), 4096LL);
    return v < 0 ? 0UL : v > 255 ? 255UL : (unsigned long)v;
}

/* R6g (docs/R6G_PLAN.md 2): the depth test the model applies -- the eight compare functions on the
   stored value, the write mask, and RB3D_CNTL.Z_ENABLE = 0 read as "no test and no depth write" */
static int
r6Zpass(int func, unsigned long nw, unsigned long old)
{
    if (func == 0) return 0;
    if (func == 1) return nw < old;
    if (func == 2) return nw <= old;
    if (func == 3) return nw == old;
    if (func == 4) return nw >= old;
    if (func == 5) return nw > old;
    if (func == 6) return nw != old;
    return 1;
}

static unsigned long
r6DepthRead(unsigned long doff, unsigned long pitch, unsigned long x, unsigned long y, int zbits)
{
    if (zbits == 24)
        return vram[(doff - WIN0 + r6Mba(pitch, x, y)) / 4UL] & 0xffffffUL;
    {
        unsigned long a = r6MbaZ16(pitch, x, y);

        return (vram[(doff - WIN0 + a) / 4UL] >> (16UL * ((a >> 1) & 1UL))) & 0xffffUL;
    }
}

/* R6h (docs/R6H_PLAN.md 2): the model's texture sampler -- nearest, the clamp PP_TXFILTER asks for,
   POT addressing (row stride = width * 4, the pitch register is not read), ST interpolated in
   1/65536 with slopes floored to that same unit.  tools/r6/tex_oracle.py mirrors this exactly. */
static long
r6TexIndex(long long v, long n, int mode)      /* v in 1/65536 texels */
{
    long t = (long)r6FloorDiv(v, 65536LL);

    if (mode == 0) {                            /* clamp to last */
        if (t < 0) t = 0;
        if (t > n - 1) t = n - 1;
        return t;
    }
    t = t % n;                                  /* wrap */
    return t < 0 ? t + n : t;
}

static unsigned long
r6Texel(unsigned long toff, unsigned long w, unsigned long u, unsigned long v)
{
    unsigned long stride = w * 4UL < 32UL ? 32UL : w * 4UL;  /* measured: max(width * 4, 32) bytes
                                                                (docs/R6H_PLAN.md 8) */

    return vram[(toff - WIN0 + v * stride + u * 4UL) / 4UL];
}

static void
r6Tri(const unsigned long *pw, unsigned long nv, unsigned long doff, unsigned long pitch, unsigned long coff,
      unsigned long cpitch, int zbits, int writes)
{
    unsigned long zv;
    int zfunc = (int)((R(0x1c2c) >> 4) & 7UL), zwrite = (int)((R(0x1c2c) >> 30) & 1UL);
    int zen = (int)((R(0x1c3c) >> 8) & 1UL);
    int textured = (R(0x1c38) & 0x10UL) != 0UL;         /* PP_CNTL.TEX_0_ENABLE (R6h) */
    unsigned long vsz = textured ? 7UL : 5UL;
    unsigned long tw = 1UL << ((R(0x2c04) >> 8) & 0xfUL), th = 1UL << ((R(0x2c04) >> 12) & 0xfUL);
    int tmode = ((R(0x2c00) >> 23) & 7UL) == 0UL ? 1 : 0;    /* 0 = wrap in the register, 2 = clamp last */
    long long SS[3], TT[3], qsx = 0, qsy = 0, qtx = 0, qty = 0;
    unsigned long t, x, y, k, col, pix, lane, cl[3], vcol[3];
    long long px[3], py[3], area, sx, sy, e, dx, dy, X16[3], Y16[3];
    int i, j, sgn, inside, inc, gouraud = ((R(0x1c4c) >> 8) & 3UL) == 2UL;

    for (t = 0; t < nv; t += 3) {
        col = pw[1 + (t + 2) * vsz + 4];        /* flat: the last vertex (SE_CNTL FLAT_SHADE_VTX_LAST) */
        zv = r6Conv(pw[1 + t * vsz + 2], zbits, 1); /* R6f: the triangle's first vertex's z */
        pix = (col & 0xff000000UL) | ((col & 0xffUL) << 16) | (col & 0xff00UL) | ((col >> 16) & 0xffUL);
        for (i = 0; i < 3; i++) {
            px[i] = r6Fix(pw[1 + (t + i) * vsz]);
            py[i] = r6Fix(pw[2 + (t + i) * vsz]);
            X16[i] = px[i] >> 20;                   /* 1/16 pixel units */
            Y16[i] = py[i] >> 20;
            vcol[i] = pw[1 + (t + i) * vsz + 4];
            if (textured) {                         /* R6h: s and t follow the colour */
                SS[i] = (long long)((double)r6f(pw[1 + (t + i) * vsz + 5]) * 65536.0);
                TT[i] = (long long)((double)r6f(pw[1 + (t + i) * vsz + 6]) * 65536.0);
            }
        }
        if (textured) {
            long long A16 = (X16[1] - X16[0]) * (Y16[2] - Y16[0]) - (X16[2] - X16[0]) * (Y16[1] - Y16[0]);

            if (A16 == 0)
                continue;
            if (A16 < 0) {
                A16 = -A16;
                qsx = -((SS[1] - SS[0]) * (Y16[2] - Y16[0]) - (SS[2] - SS[0]) * (Y16[1] - Y16[0]));
                qsy = -((SS[2] - SS[0]) * (X16[1] - X16[0]) - (SS[1] - SS[0]) * (X16[2] - X16[0]));
                qtx = -((TT[1] - TT[0]) * (Y16[2] - Y16[0]) - (TT[2] - TT[0]) * (Y16[1] - Y16[0]));
                qty = -((TT[2] - TT[0]) * (X16[1] - X16[0]) - (TT[1] - TT[0]) * (X16[2] - X16[0]));
            } else {
                qsx = (SS[1] - SS[0]) * (Y16[2] - Y16[0]) - (SS[2] - SS[0]) * (Y16[1] - Y16[0]);
                qsy = (SS[2] - SS[0]) * (X16[1] - X16[0]) - (SS[1] - SS[0]) * (X16[2] - X16[0]);
                qtx = (TT[1] - TT[0]) * (Y16[2] - Y16[0]) - (TT[2] - TT[0]) * (Y16[1] - Y16[0]);
                qty = (TT[2] - TT[0]) * (X16[1] - X16[0]) - (TT[1] - TT[0]) * (X16[2] - X16[0]);
            }
            qsx = r6FloorDiv(qsx * 16LL, A16);  qsy = r6FloorDiv(qsy * 16LL, A16);
            qtx = r6FloorDiv(qtx * 16LL, A16);  qty = r6FloorDiv(qty * 16LL, A16);
        }
        area = (px[1] - px[0]) * (py[2] - py[0]) - (px[2] - px[0]) * (py[1] - py[0]);
        if (area == 0)
            continue;
        sgn = area > 0 ? 1 : -1;
        for (y = 0; y < 64UL; y++)
            for (x = 0; x < 64UL; x++) {
                sx = (long long)x * 16777216LL + 8388608LL;
                sy = (long long)y * 16777216LL + 8388608LL;
                inside = 1;
                for (i = 0; i < 3 && inside; i++) {
                    j = (i + 1) % 3;
                    dx = (px[j] - px[i]) * sgn;
                    dy = (py[j] - py[i]) * sgn;
                    e = dx * (sy - py[i]) - dy * (sx - px[i]);
                    inc = (dy == 0 && dx > 0) || dy < 0;    /* top or left, y down */
                    if (e < 0 || (e == 0 && !inc))
                        inside = 0;
                }
                if (!inside)
                    continue;
                /* R6k: rule H, as the rectangle path already applies it (docs/R6B_PLAN.md 5) --
                   RE_WIDTH_HEIGHT always, RE_TOP_LEFT only with SCISSOR_ENABLE.  The auxiliary
                   scissor is not modelled: tools/r6/sim_r6.py compares the words instead */
                if (x > (R(0x1c44) & 0xffffUL) || y > (R(0x1c44) >> 16))
                    continue;
                if ((R(0x1c50) & 2UL) && (x < (R(0x26c0) & 0xffffUL) || y < (R(0x26c0) >> 16)))
                    continue;
                /* R6g: the test decides the colour and (with the write bit) the depth */
                if (zen && !r6Zpass(zfunc, zv, r6DepthRead(doff, pitch, x, y, zbits)))
                    continue;
                if (zen && zwrite) {
                    if (zbits == 24) {
                        k = (doff - WIN0 + r6Mba(pitch, x, y)) / 4UL;
                        vram[k] = (vram[k] & 0xff000000UL) | zv;
                    } else {                        /* R6f: the halfword, the other half kept */
                        unsigned long a = r6MbaZ16(pitch, x, y), sh = 16UL * ((a >> 1) & 1UL);

                        k = (doff - WIN0 + a) / 4UL;
                        vram[k] = (vram[k] & ~(0xffffUL << sh)) | (zv << sh);
                    }
                }
                if (writes && x < cpitch && textured) {     /* R6h: the texel decides the pixel */
                    long long sx16 = (long long)x * 16 + 8, sy16 = (long long)y * 16 + 8;
                    long long sv = SS[0] + r6FloorDiv(qsx * (sx16 - X16[0]) + qsy * (sy16 - Y16[0]), 16LL);
                    long long tv = TT[0] + r6FloorDiv(qtx * (sx16 - X16[0]) + qty * (sy16 - Y16[0]), 16LL);
                    unsigned long uu = (unsigned long)r6TexIndex(sv * (long long)tw, (long)tw, tmode);
                    unsigned long vvv = (unsigned long)r6TexIndex(tv * (long long)th, (long)th, tmode);

                    k = (coff - WIN0 + 4UL * (x + cpitch * y)) / 4UL;
                    vram[k] = r6Texel(R(0x2d00), tw, uu, vvv);
                    continue;
                }
                if (writes && x < cpitch) {
                    if (gouraud) {                  /* word r g b a -> pixel a r g b */
                        pix = 0;
                        for (lane = 0; lane < 4UL; lane++) {
                            static const int from[4] = { 16, 8, 0, 24 };  /* pixel byte l <- word shift */
                            for (i = 0; i < 3; i++)
                                cl[i] = (vcol[i] >> from[lane]) & 0xffUL;
                            pix |= r6Gouraud(X16, Y16, cl, (long long)x * 16 + 8, (long long)y * 16 + 8) << (8UL * lane);
                        }
                    }
                    k = (coff - WIN0 + 4UL * (x + cpitch * y)) / 4UL;
                    vram[k] = pix;
                }
            }
    }
}

static void
r6Draw(const unsigned long *pw, unsigned long cnt)
{
    unsigned long doff = R(0x1c24), pitch = R(0x1c28) & 0x1ff8UL, coff = R(0x1c40), tl = R(0x26c0), wh = R(0x1c44);
    unsigned long cpitch = R(0x1c48) & 0x1ff8UL, fmt = R(0x2088), vsz, col = 0, pix = 0;
    unsigned long x, y, z24, k;
    long gx1, gy1, gx2, gy2;
    int colour, writes;
    float z;

    r6Draws++;
    /* SE_VAP_CNTL_STATUS is recorded, not gated (docs/R6_PLAN.md 8-2 m1), and R200_RE_CNTL
       differs by case (docs/R6B_PLAN.md 5): the stream comparison in tools/r6/sim_r6.py is
       what proves the words.  R6c (docs/R6C_PLAN.md 6): the colour path is either all off
       (PP_CNTL 0, fmt Z0|W0) or all Mesa's (PP_CNTL TEX_BLEND_0, fmt + PK_RGBA, blend stage 0
       passing the diffuse colour) -- anything between is outside the model */
    /* R6g: the compare and write bits vary by case; the format and the stencil fields do not */
    /* R6j: bits 0 (ALPHA_BLEND_ENABLE) and 3 (ROUND_ENABLE) may be set for the second draw; this
       model has no blend unit, so it overwrites -- tools/r6/sim_r6.py compares the words instead */
    if (((R(0x1c3c) & ~0x9UL) != 0x1902UL && (R(0x1c3c) & ~0x9UL) != 0x1802UL) ||
        (R(0x1c2c) & ~0x4000007fUL) != 0x02227000UL || ((R(0x1c2c) & 0xfUL) != 0UL && (R(0x1c2c) & 0xfUL) != 2UL) ||
        (R(0x20b0) != 0x300UL && R(0x20b0) != 0x700UL) ||      /* R6i: VTX_W0_FMT in PF */
        R(0x2080) != 0x00240000UL || (R(0x2180) != 0UL && R(0x2180) != 0x10000UL) ||
        R(0x1d7c) != 0UL || R(0x1d60) != 0UL ||
        (R(0x208c) != 0UL && !(R(0x208c) == 2UL && (R(0x1c38) & 0x10UL))))   /* R6h: ST on unit 0 */
        fail("3D state is not the precedent's", R(0x1c3c), R(0x1c2c));
    /* R6i-2: PP_CNTL bit 10 (FILTER_ROUND_MODE) picks a rounding inside the texture filter, which
       this model does not have -- it is recorded by the stream comparison, not acted on here */
    /* G4-3 K2: the alpha test enable (PP_CNTL bit 23) is orthogonal to the texture pairing, and
       PP_MISC may carry only the reference byte and the compare (r200_reg.h 33-43) */
    if ((R(0x1c14) & ~0x7ffUL) != 0UL)
        fail("PP_MISC carries more than the alpha reference and compare", R(0x1c14), 0);
    if (!(((R(0x1c38) & ~0x800000UL) == 0UL && fmt == 3UL) || ((R(0x1c38) & ~0x800000UL) == 0x1000UL && fmt == 0x803UL) ||
          ((R(0x1c38) & ~0x800400UL) == 0x1010UL && fmt == 0x803UL && R(0x208c) == 2UL)))   /* R6h: the texture unit */
        fail("PP_CNTL and SE_VTX_FMT_0 are not a modelled pair", R(0x1c38), fmt);
    colour = (fmt == 0x803UL);
    (void)0;
    /* R6c: the diffuse pass-through; R6h: the same shape but arg A = R0, the sampled texel */
    if (colour && ((R(0x2f00) != 0x1000UL && R(0x2f00) != 0x0010000aUL) || R(0x2f04) != 0x11000UL ||
                   (R(0x2f08) != 0x1000UL && R(0x2f08) != 0x0010000aUL) || R(0x2f0c) != 0x11000UL ||
                   (R(0x2f00) == 0x0010000aUL) != ((R(0x1c38) & 0x10UL) != 0UL)))
        fail("blend stage 0 is not the modelled pass-through", R(0x2f00), R(0x2f04));
    if (R(0x1d84) != 0UL && R(0x1d84) != 0xffffffffUL)
        fail("a partial plane mask is outside the model", R(0x1d84), 0);
    vsz = colour ? 5UL : 4UL;
    if ((pw[0] & 0xfUL) == 4UL) {                /* R6d: TRIANGLES, colour on, whole-buffer scissor */
        unsigned long nv = pw[0] >> 16;

        if ((R(0x1c38) & 0x10UL) != 0UL)        /* R6h: the textured vertex is two words longer */
            vsz = 7UL;
        /* R6k: the clip is no longer required to be the whole buffer -- r6Tri applies rule H
           itself now (docs/R6K_PLAN.md 9), and RE_CNTL 0 is one of the cases */
        if (!colour || R(0x1d84) != 0xffffffffUL || (pw[0] & 0xffffUL) != 0x74UL || nv == 0 || nv % 3UL != 0 ||
            cnt != 1UL + nv * vsz ||
            (R(0x1c50) != 0UL && R(0x1c50) != 2UL && R(0x1c50) != 0xaUL)) {   /* R6i: PERSPECTIVE_ENABLE */
            fail("a triangle packet outside the model", pw[0], cnt);
            return;
        }
        if (doff < WIN0 || doff + pitch * 64UL * 4UL > WIN0 + sizeof vram || (doff & 0xfffUL) != 0UL ||
            coff < WIN0 || coff + cpitch * 64UL * 4UL > WIN0 + sizeof vram) {
            fail("a triangle's buffers outside the block", doff, coff);
            return;
        }
        r6Tri(pw, nv, doff, pitch, coff, cpitch, (R(0x1c2c) & 0xfUL) == 0UL ? 16 : 24, 1);
        return;
    }
    if (cnt != 1UL + 3UL * vsz) {
        fail("the IMMD count and SE_VTX_FMT_0 disagree", cnt, fmt);
        return;
    }
    /* G3c: the 24-bit precedent (R6a's boxes) or the 16-bit clear (0x42227070: the client's
       format with Z_TEST_ALWAYS -- the reference builds its clear word from the client's
       depth_fmt, radeon_cp.c 1215-1221); nothing else */
    if (R(0x1c2c) != 0x42227072UL && R(0x1c2c) != 0x42227070UL)
        fail("a box outside the 24-bit precedent or the 16-bit clear", R(0x1c2c), 0);
    if (pw[0] != 0x00030038UL && pw[0] != 0x00030078UL)
        fail("VF_CNTL is not RECT_LIST | WALK_RING | 3 (| COLOR_ORDER_RGBA)", pw[0], 0);
    if (doff < WIN0 || doff + pitch * 64UL * 4UL > WIN0 + sizeof vram || (doff & 0xfffUL) != 0UL) {
        fail("a 3D depth write outside the block", doff, pitch);
        return;
    }
    if (coff < WIN0 || coff + cpitch * 64UL * 4UL > WIN0 + sizeof vram) {
        fail("the colour buffer points outside the block", coff, R(0x1c48));
        return;
    }
    if (colour) {
        /* flat shading, last vertex (SE_CNTL 0x480055de); Mesa's colour is bytes r g b a
           with COLOR_ORDER_RGBA, the pixel is ARGB8888 (spantmp2.h) -- without the bit the
           model reads the word as b g r a */
        col = pw[1 + 2 * vsz + 4];
        if (pw[1 + 4] != col || pw[1 + vsz + 4] != col)
            fail("the three vertex colours differ", pw[1 + 4], col);
        if (pw[0] & 0x40UL)
            pix = (col & 0xff000000UL) | ((col & 0xffUL) << 16) | (col & 0xff00UL) | ((col >> 16) & 0xffUL);
        else
            pix = col;
    }
    writes = colour && R(0x1d84) == 0xffffffffUL;
    /* RECT_LIST: (x1,y1) (x1,y2) (x2,y2) covers [x1,x2) x [y1,y2); the clip is inclusive */
    gx1 = (long)r6f(pw[1]); gy1 = (long)r6f(pw[2]);
    gx2 = (long)r6f(pw[1 + 2 * vsz]); gy2 = (long)r6f(pw[2 + 2 * vsz]);
    z = r6f(pw[3]);
    z24 = r6Conv(pw[3], 24, 0);                 /* R6f: exact floor, what the float product gave */
    (void)z;
    for (y = 0; y < 64UL; y++)
        for (x = 0; x < pitch; x++) {
            if ((long)x < gx1 || (long)x >= gx2 || (long)y < gy1 || (long)y >= gy2)
                continue;
            /* rule H (docs/R6B_PLAN.md 5): RE_WIDTH_HEIGHT always, RE_TOP_LEFT only
               with SCISSOR_ENABLE -- measured for RE_CNTL 0 on e3ec4d0c */
            if (x > (wh & 0xffffUL) || y > (wh >> 16))
                continue;
            if ((R(0x1c50) & 2UL) && (x < (tl & 0xffffUL) || y < (tl >> 16)))
                continue;
            if ((R(0x1c2c) & 0xfUL) == 0UL) {          /* G3c: 16-bit, the half-word r6Tri writes */
                unsigned long a = r6MbaZ16(pitch, x, y), sh = 16UL * ((a >> 1) & 1UL);
                k = (doff - WIN0 + (a & ~3UL)) / 4UL;
                vram[k] = (vram[k] & ~(0xffffUL << sh)) | (r6Conv(pw[3], 16, 0) << sh);
            } else {
                k = (doff - WIN0 + r6Mba(pitch, x, y)) / 4UL;
                vram[k] = (vram[k] & 0xff000000UL) | z24;
            }
            if (writes && x < cpitch) {
                k = (coff - WIN0 + 4UL * (x + cpitch * y)) / 4UL;     /* linear: pitch 64, no tile bits */
                vram[k] = pix;
            }
        }
}

