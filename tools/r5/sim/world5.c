/*
 * world5.c - a fake RV280 Command Processor behind a PCI GART, for osrdn_cp.m
 * (docs/R5_PLAN.md 4, 7-2 B13).  THIS PROVES "THE DRIVER MATCHES OUR MODEL", NOT
 * THE HARDWARE: the model is written from the same references the driver was.
 * Only the machine judges the hardware.
 *
 * The model:
 *   - MMIO 0x4000 bytes; any access past it fails.  RBBM_STATUS: FIFO free
 *     slots and ACTIVE while the CP has words to execute;
 *   - PLL behind CLOCK_CNTL_INDEX (byte) / DATA, written only with PLL_WR_EN;
 *   - ME RAM: CP_ME_RAM_ADDR resets the index, then DATAH/DATAL pairs, DATAH
 *     first; the CP runs only if all 256 pairs equal the table (with
 *     simNeedReset, also only after a soft reset of the CP following the load);
 *   - the block lives at a fake physical address; the GPU reads a SEPARATE copy
 *     of it that is refreshed only by osrdn_cpu_wbinvd() -- stricter than an
 *     x86 that snoops, so a missing flush shows;
 *   - GART: a GPU address in [AIC_LO, AIC_HI] with translation on reads its PTE
 *     from the table at AIC_PT_BASE; anything that resolves outside the block,
 *     translation off, or an address inside a live AGP aperture, is a hang on the
 *     machine and fails here;
 *   - the CP fetches from RB_BASE, RPTR up to WPTR (mod the ring size from
 *     RB_CNTL), 32 bytes ahead of WPTR as prefetch (read, not executed), and
 *     executes PACKET0 (register writes) and PACKET2; anything else fails;
 *   - writeback: with RB_NO_UPDATE clear the CP writes RPTR to RPTR_ADDR, and
 *     with SCRATCH_UMSK bits set it writes scratch values to SCRATCH_ADDR --
 *     through the GART, into the block, where the canaries see it;
 *   - progress: the words execute over a few status reads (ACTIVE meanwhile).
 */

