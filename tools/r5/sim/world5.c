static unsigned long pw[CP_R6_WORDS];       /* R6l: one packet's words (the biggest is 1201) */

static void
cpStep(unsigned long n)
{
    unsigned long mask = ringWords() - 1UL, hdr, cnt, reg, k, ran = 0;
    int had = pendingWords > 0;

    while (n-- > 0 && pendingWords > 0) {
        ran++;
        hdr = gpuRead(R(0x0700) + rptr * 4UL);
        if (hdr == CP_PACKET2) {
            rptr = (rptr + 1UL) & mask;
            pendingWords--;
            continue;
        }
        if ((hdr & 0xc000ffffUL) == 0xc0003500UL) {      /* any 3D_DRAW_IMMD_2 (R6l: the count varies) */
            unsigned long pn = ((hdr >> 16) & 0x3fffUL) + 1UL;    /* R6l: the packets grew */
            if (pn > (unsigned long)(sizeof pw / sizeof pw[0])) {
                fail("a 3D packet longer than the model's buffer", hdr, pn);
                pendingWords = 0;
                return;
            }
            if (pn + 1UL > pendingWords) {
                fail("a 3D packet runs past WPTR", hdr, pendingWords);
                pendingWords = 0;
                return;
            }
            /* M3f: a 3D packet MAY cross the ring's end -- the words are read
               through the mask below, as the CP reads them (docs/M3F_PLAN.md).
               The rule that failed it here was the driver's old caution, not a
               measurement, and the caution was what latched the card (M3e). */
            for (k = 0; k < pn; k++)
                pw[k] = gpuRead(R(0x0700) + ((rptr + 1UL + k) & mask) * 4UL);
            if (simTrace3d) {
                printf("R6P3 %08lx", hdr);
                for (k = 0; k < pn; k++)
                    printf(" %08lx", pw[k]);
                printf("\n");
            }
            r6Draw(pw, pn);
            rptr = (rptr + pn + 1UL) & mask;
            pendingWords -= pn + 1UL;
            continue;
        }
        if ((hdr & 0xc000ffffUL) == 0xc0009a00UL) {      /* G3b: CNTL_PAINT_MULTI, the 2D solid fill */
            unsigned long pn = ((hdr >> 16) & 0x3fffUL) + 1UL, gmc, po, colour, xy, wh, addr, pitch, x, y, w, h, yy, xx, k2;

            if (pn != 5UL || pn + 1UL > pendingWords) {
                fail("PAINT_MULTI is not the reference's five words", hdr, pn);
                pendingWords = 0;
                return;
            }
            gmc = gpuRead(R(0x0700) + ((rptr + 1UL) & mask) * 4UL);
            po = gpuRead(R(0x0700) + ((rptr + 2UL) & mask) * 4UL);
            colour = gpuRead(R(0x0700) + ((rptr + 3UL) & mask) * 4UL);
            xy = gpuRead(R(0x0700) + ((rptr + 4UL) & mask) * 4UL);
            wh = gpuRead(R(0x0700) + ((rptr + 5UL) & mask) * 4UL);
            /* DST_PITCH_OFFSET_CNTL | BRUSH_SOLID_COLOR | DST_32BPP | ROP3_P: what a solid paint needs */
            if ((gmc & 0x2UL) == 0UL || ((gmc >> 4) & 0xfUL) != 13UL || ((gmc >> 8) & 0xfUL) != 6UL ||
                ((gmc >> 16) & 0xffUL) != 0xf0UL) {
                fail("PAINT_MULTI GMC is not a solid 32 bpp paint", gmc, 0);
                pendingWords = 0;
                return;
            }
            addr = (po & 0x3fffffUL) << 10;
            pitch = (po >> 22) * 64UL;
            x = xy >> 16; y = xy & 0xffffUL; w = wh >> 16; h = wh & 0xffffUL;
            if (addr < WIN0 || pitch == 0UL) {
                fail("PAINT_MULTI destination is not in the block", addr, pitch);
                pendingWords = 0;
                return;
            }
            for (yy = 0; yy < h; yy++)
                for (xx = 0; xx < w; xx++) {
                    k2 = (addr - WIN0 + (y + yy) * pitch + (x + xx) * 4UL) / 4UL;
                    if (k2 >= sizeof vram / sizeof vram[0]) {
                        fail("PAINT_MULTI paints past the block", k2, 0);
                        pendingWords = 0;
                        return;
                    }
                    vram[k2] = colour;
                }
            paints++;
            rptr = (rptr + pn + 1UL) & mask;
            pendingWords -= pn + 1UL;
            continue;
        }
        if ((hdr & 0xc0000000UL) != 0UL) {
            fail("a packet type outside the model", hdr, rptr);
            pendingWords = 0;
            return;
        }
        cnt = ((hdr >> 16) & 0x3fffUL) + 1UL;
        reg = (hdr & 0x1fffUL) << 2;
        if (cnt + 1UL > pendingWords) {
            fail("a packet runs past WPTR", hdr, pendingWords);
            pendingWords = 0;
            return;
        }
        for (k = 0; k < cnt; k++)
            cpRegWrite(reg + 4UL * k, gpuRead(R(0x0700) + ((rptr + 1UL + k) & mask) * 4UL));
        rptr = (rptr + cnt + 1UL) & mask;
        pendingWords -= cnt + 1UL;
    }
    R(0x0710) = rptr;
    if (ran > 0 && (R(0x0704) & 0x08000000UL) == 0UL)
        gpuWrite(R(0x070c), rptr);                      /* rptr writeback, when the CP moved */
    /* G4-3 K1: the ring just drained -- the armed drain starts the engine's slow drawing */
    if (had && pendingWords == 0 && simSlowIdleDrains > 0 && --simSlowIdleDrains == 0)
        simSlowIdle = simSlowIdleReads;
}

/* G3: the raw ring words between the old RPTR and the WPTR just written, BEFORE
   the fake CP runs them -- R6W prints only the register writes it decoded, and
   the present test must see the headers and the padding as a group */
#define CAP_WORDS 96
static unsigned long capWords[CAP_WORDS], capCount;

static void
wptrWritten(unsigned long w)
{
    unsigned long words = ringWords(), k, pre;

    if (w >= words) {
        fail("WPTR written outside the ring", w, words);
        return;
    }
    R(0x0714) = w;
    if (!cpRuns())
        return;
    csqStatV = (csqStatV & ~0xfffffUL) | 16UL | (16UL << 10);
    pendingWords = (w - rptr) & (words - 1UL);
    capCount = (pendingWords < CAP_WORDS) ? pendingWords : CAP_WORDS;
    for (k = 0; k < capCount; k++)
        capWords[k] = gpuRead(R(0x0700) + ((rptr + k) & (words - 1UL)) * 4UL);
    /* prefetch 32 bytes past WPTR: reads that must translate */
    for (k = 0; k < 8; k++) {
        pre = (w + k) & (words - 1UL);
        (void)gpuRead(R(0x0700) + pre * 4UL);
    }
    if (simStrayGuard) {
        (void)gpuRead(CP_GART_BASE + 10UL * CP_PAGE);   /* a fetch of a guard page */
        cpRegWrite(0x15f4, CP_PACKET2);
        simStrayGuard = 0;
    }
    if (simGpuWritesRing) {
        gpuWrite(R(0x0700) + 5UL * 4UL, 0xdead0000UL);
        simGpuWritesRing = 0;
    }
}

/* ---- MMIO -------------------------------------------------------------------- */
unsigned long
rdnMmioRead32(vm_address_t base, unsigned int off)
{
    (void)base;
    if (off + 4 > MMIO_BYTES) {
        fail("MMIO read outside the map", off, 0);
        return 0xffffffffUL;
    }
    trace('r', off, 0);
    if (watchLatch && off != 0x0e40)
        cpuReadsAfterLatch++;
    if (off == 0x0e40) {
        statusReads++;
        cpStep(64);
        if (simFifoJamAfter > 0 && --simFifoJamAfter == 0)
            simFifoJamAfter = -1;
        if (simFifoJamAfter < 0)
            return 0UL;                                 /* FIFO full, idle: nothing can be queued */
        if (pendingWords == 0 && simSlowIdle > 0) {
            simSlowIdle--;
            return 64UL | 0x80000000UL;                 /* G4-3 K1: fetched, still drawing */
        }
        return 64UL | ((pendingWords > 0 || simActiveAtBoot) ? 0x80000000UL : 0UL);
    }
    if (off == 0x0710) {
        cpStep(64);
        return rptr;
    }
    if (off == 0x000c)
        return pll[pllIndex];
    if ((off == 0x07f8 || off == 0x07fc) && (pendingWords > 0 || simActiveAtBoot))
        fail("a CSQ status read while the engine is busy (status first, the R4 rule)", off, pendingWords);
    if (off == 0x07f8)                                  /* CP_CSQ_STAT: a record, never a gate */
        return simCsqQueued ? ((csqStatV & ~0xfffffUL) | 16UL | (17UL << 10)) : csqStatV;
    return mmio[off / 4];
}

void
rdnMmioWrite32(vm_address_t base, unsigned int off, unsigned long v)
{
    (void)base;
    if (off + 4 > MMIO_BYTES) {
        fail("MMIO write outside the map", off, v);
        return;
    }
    trace('w', off, v);
    if (watchLatch)
        cpuWritesAfterLatch++;
    switch (off) {
    case 0x000c:
        if (!pllWrEn)
            fail("a PLL write without PLL_WR_EN", (unsigned long)pllIndex, v);
        else
            pll[pllIndex] = v;
        return;
    case 0x0008:
        mmio[0x0008 / 4] = v;
        pllIndex = (int)(v & 0x3fUL);
        pllWrEn = (v & 0x80UL) != 0UL;
        return;
    case 0x07d4:
        meIdx = 0;
        meLastHigh = 0;
        return;
    case 0x07dc:
        if (meLastHigh)
            meBad = 1;
        if (meIdx < 512)
            meram[meIdx++] = v;
        meWrites++;
        meLastHigh = 1;
        resetAfterLoad = 0;
        return;
    case 0x07e0:
        if (!meLastHigh)
            meBad = 1;
        if (meIdx < 512)
            meram[meIdx++] = v;
        meWrites++;
        meLastHigh = 0;
        return;
    case 0x00f0:
        if ((v & 1UL) && meWrites == 512)
            resetAfterLoad = 1;
        if ((v & 1UL) && simResetHeals) {          /* M3j: SOFT_RESET_CP un-wedges the fake CP */
            simNeverAdvance = 0;
            simResetHeals = 0;
        }
        if ((v & 0x7fUL) && simResetClearsAic) {
            R(0x01d0) = 0;
            simResetClearsAic = 0;
        }
        break;
    case 0x0714:
        wptrWritten(v);
        return;
    case 0x0700:
    case 0x0704:
        csqStatV &= ~0xfffffUL;
        break;
    case 0x01e0:
        if (simHiMode == 1)
            v &= ~0xfffUL;
        else if (simHiMode == 2 && v != 0UL)
            v = 0x207ff7ffUL;
        else if (simHiMode == 3 && v != 0UL)
            v = 0x20400000UL;
        break;
    case 0x014c:
        if (simAgpMangle)
            v &= 0xffff0000UL;
        break;
    case 0x15f4:
        if (simReg5Mangle && v == CP_REG5_POISON)
            v = 0x5a5a0006UL;
        break;
    case 0x070c:
        if (simRptrDrift)
            rptr = (rptr + 1UL) & 4095UL;           /* the CP pointer moves with nothing asked */
        break;
    case 0x01d0:
        if ((v & 1UL) == 0UL && (R(0x01d0) & 1UL) && (R(0x0740) & 0xf0000000UL))
            fail("GART translation turned off while the CSQ is on", R(0x01d0), R(0x0740));
        break;
    case 0x0740:
        if ((v & 0xf0000000UL) && (R(0x01d0) & 1UL) == 0UL)
            fail("the CSQ turned on with the GART off", v, R(0x01d0));
        if ((v & 0xf0000000UL) == 0UL) {
            rptr = 0;                       /* the CSQ off: RPTR reads 0 (boot eae3072b) */
            pendingWords = 0;               /* and the fake CP stops fetching */
        }
        break;
    case 0x0e40:
    case 0x0710:
        fail("a write to a read-only status register", off, v);
        return;
    }
    mmio[off / 4] = v;
}

void
rdnMmioWrite8(vm_address_t base, unsigned int off, unsigned char v)
{
    (void)base;
    trace('b', off, v);
    if (watchLatch)
        cpuWritesAfterLatch++;
    if (off == 0x0008) {
        pllIndex = v & 0x3f;
        pllWrEn = (v & 0x80) != 0;
        mmio[0x0008 / 4] = (mmio[0x0008 / 4] & ~0xffUL) | v;
        return;
    }
    fail("a byte write outside CLOCK_CNTL_INDEX", off, v);
}

